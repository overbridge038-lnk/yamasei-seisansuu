# 2026-11-25o：未処置NGがあるとCSV出力も止める（ポカヨケ）／客先QR（「,,,」「j」「g」）はNGのまま理由を分かりやすく
import os, pathlib
HERE=pathlib.Path(__file__).resolve().parent
INDEX=(HERE.parent/'index.html').as_uri()
os.chdir(HERE/'fixtures')
CHROME=os.environ.get('CHROME') or None
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch(executable_path=CHROME,args=['--no-sandbox'])
    ctx=b.new_context(accept_downloads=True,viewport={'width':800,'height':1200}); pg=ctx.new_page()
    errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    R=[]
    def chk(n,c,i=""): R.append(c); print(("PASS " if c else "FAIL ")+n,i)
    pg.goto(INDEX); pg.evaluate("localStorage.clear()"); pg.reload()
    chk("verを表示（2026-11-25o）","2026-11-25o" in pg.content())
    A="028031,JH001-001830-1,25,8"
    print("== 1. 客先QRの判定")
    for raw in [",,,","j","g"," , , ","JG"]:
        r=pg.evaluate("(x)=>extractQR(toHalf(x))",raw)
        chk("客先QR："+repr(raw),(not r['ok']) and r['matchedKey']=="客先QR" and "客先QR" in r['reason'] and "かんばん" in r['reason'],r)
    for raw in ["ZZZ","1","JH001","028031,,"]:
        r=pg.evaluate("(x)=>extractQR(toHalf(x))",raw)
        chk("客先QRにしない："+repr(raw),r['matchedKey']!="客先QR",r)
    r=pg.evaluate("(x)=>extractQR(toHalf(x))",A); chk("通常のQRはOKのまま",r['ok'],r)
    pg.click('[data-pick="1"]')
    pg.evaluate("(a)=>commitQRRecords([a])",A)
    chk("NGなし：CSV出力できる",not pg.is_disabled('#bCsv'))
    with pg.expect_download() as d: pg.evaluate("$('bCsv').click()")
    chk("NGなし：CSVが出る",d.value.suggested_filename.endswith('.csv'))
    pg.evaluate("commitQRRecords([',,,'])")
    chk("客先QRはNGとして記録・アンドンに出る",pg.inner_text('#ngAndonN')=="1")
    chk("読取結果に客先QRの理由","客先QR" in pg.inner_text('#scanResult'),pg.inner_text('#scanResult'))
    pg.click('#ngAndon')
    t=pg.inner_text('#ngList'); chk("NG一覧に理由「客先QR（品番なし）」","客先QR（品番なし）" in t,t[:120])
    opts=pg.evaluate("[...document.querySelector('#ngList [data-x=\"sel\"]').options].map(o=>o.text)")
    chk("対象外の理由に「客先QRを読んだ」",any("客先QR" in o for o in opts),opts)
    pg.click('#ngClose')
    print("== 2. 未処置NGがあるとCSV出力を止める")
    chk("CSVボタンが押せない",pg.is_disabled('#bCsv'))
    note=pg.evaluate("[$('csvBlockNote').hidden,$('csvBlockNote').textContent]")
    chk("止めた理由を表示",(not note[0]) and "未処置NG" in note[1],note)
    got=[]; pg.on('download',lambda d:got.append(d))
    pg.evaluate("$('bCsv').disabled=false; $('bCsv').click()"); pg.wait_for_timeout(500)
    chk("出力処理でも止める（ボタンを無理に押しても出ない）",not got,len(got))
    chk("Excel出荷報告も止まっている",pg.is_disabled('#bXlsx') and pg.is_disabled('#bXlsxAll'))
    print("== 3. 別の便のNGではCSVを止めない／退避は止めない")
    pg.click('[data-pick="2"]'); pg.evaluate("(a)=>commitQRRecords([a])",A)
    pg.evaluate("state.bin='2'; render()")
    chk("2便を対象：1便のNGでは止めない",not pg.is_disabled('#bCsv') and pg.evaluate("$('csvBlockNote').hidden"))
    with pg.expect_download() as d: pg.evaluate("rescue('csv')")
    chk("CSVで退避はNGがあっても出せる",d.value.suggested_filename.endswith('.csv'))
    pg.evaluate("state.bin='all'; render()")
    chk("全便を対象：止める",pg.is_disabled('#bCsv'))
    print("== 4. 処置すると出せる")
    pg.click('#ngAndon'); it=pg.query_selector('#ngList .ngItem')
    it.query_selector('[data-act="ex"]').click(); it.query_selector('[data-x="sel"]').select_option(label="客先QRを読んだ（かんばんは別に読んだ）"); it.query_selector('[data-act="exok"]').click()
    pg.click('#ngClose')
    chk("対象外で処置→CSV出力できる",not pg.is_disabled('#bCsv') and pg.evaluate("$('csvBlockNote').hidden"))
    chk("JSエラーなし",not errs,errs)
    print("RESULT",sum(R),"/",len(R))
