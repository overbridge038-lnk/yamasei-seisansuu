# 2026-11-25p：読取欄での手入力。手で打つと自動確定しない／品番なら数量欄→1箱記録／数字だけ等は「違いますよ！」だけ（記録しない）
import os, pathlib
HERE=pathlib.Path(__file__).resolve().parent
INDEX=(HERE.parent/'index.html').as_uri()
os.chdir(HERE/'fixtures')
CHROME=os.environ.get('CHROME') or None
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch(executable_path=CHROME,args=['--no-sandbox'])
    pg=b.new_page(viewport={'width':800,'height':1200})
    errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    R=[]
    def chk(n,c,i=""): R.append(c); print(("PASS " if c else "FAIL ")+n,i)
    pg.goto(INDEX); pg.evaluate("localStorage.clear()"); pg.reload()
    chk("ver 2026-11-25p","2026-11-25p" in pg.content())
    total=lambda: pg.evaluate("tally().total")
    ng=lambda: pg.evaluate("untreatedNg('all').length")
    A="028031,JH001-001810-1,20,45"
    print("== 1. 便なしで手入力ボタン")
    pg.click('#bHandInput'); chk("便なし：手入力モードにならない",not pg.is_visible('#handHint'))
    pg.click('[data-pick="1"]')
    print("== 2. ハンディ（速い入力）は今までどおり")
    pg.focus('#scanIn'); pg.keyboard.type(A,delay=5); pg.keyboard.press('Enter'); pg.wait_for_timeout(300)
    chk("ハンディ読取：OKで記録",pg.evaluate("tally().hit")==1)
    pg.focus('#scanIn'); pg.keyboard.type(A,delay=5); pg.wait_for_timeout(400)
    chk("ハンディ読取（Enterなし）：自動で確定",pg.evaluate("tally().hit")==2 and pg.input_value('#scanIn')=="")
    pg.focus('#scanIn'); pg.keyboard.type("028031",delay=5); pg.keyboard.press('Enter'); pg.wait_for_timeout(300)
    chk("ハンディの切れ端はNGで記録（今までどおり）",ng()==1,ng())
    pg.focus('#scanIn'); pg.keyboard.type(",,,",delay=5); pg.keyboard.press('Enter'); pg.wait_for_timeout(300)
    chk("ハンディの客先QRはNGで記録",ng()==2,ng())
    n0=total()
    print("== 3. 手で数字を打つ")
    pg.focus('#scanIn'); pg.keyboard.type("30",delay=180); pg.wait_for_timeout(500)
    chk("手で打つと自動で確定しない（欄に残る）",pg.input_value('#scanIn')=="30" and total()==n0,pg.input_value('#scanIn'))
    chk("手入力中の案内と「確定」ボタン",pg.is_visible('#handHint') and pg.is_visible('#bHandCommit'))
    pg.keyboard.press('Enter'); pg.wait_for_timeout(200)
    chk("数字だけ：「違いますよ！」を表示",pg.is_visible('#handWarn') and "違いますよ" in pg.inner_text('#handWarn') and "数量" in pg.inner_text('#handWarn'),pg.inner_text('#handWarn'))
    chk("数字だけ：記録しない・NGにしない",total()==n0 and ng()==2,(total(),ng()))
    chk("欄は空・手入力モード終わり",pg.input_value('#scanIn')=="" and not pg.is_visible('#handHint'))
    pg.focus('#scanIn'); pg.keyboard.type("5",delay=180); pg.wait_for_timeout(500); pg.keyboard.press('Enter'); pg.wait_for_timeout(200)
    chk("1文字＋間があいてEnter：注意だけ",total()==n0 and "違いますよ" in pg.inner_text('#handWarn'))
    pg.click('#bHandInput'); pg.keyboard.type("ZZ-99999-9",delay=120); pg.click('#bHandCommit'); pg.wait_for_timeout(200)
    chk("一覧にない品番：注意だけ","品番一覧にありません" in pg.inner_text('#handWarn') and total()==n0)
    print("== 4. 手で品番を入れて数量→1箱")
    pg.click('#bHandInput'); chk("「品番を手で入力する」で手入力モード",pg.is_visible('#handHint'))
    pg.keyboard.type("jh001-001810-1",delay=120); pg.click('#bHandCommit'); pg.wait_for_timeout(200)
    chk("品番OK：数量欄が出る",pg.is_visible('#handQty') and pg.inner_text('#hqPart')=="JH001-001810-1")
    chk("数量の初期値は前に読んだ収容数20",pg.input_value('#hqQty')=="20",pg.input_value('#hqQty'))
    pg.fill('#hqQty',''); pg.click('#hqAdd'); chk("数量が空なら止める",pg.is_visible('#handQty') and "数量" in pg.inner_text('#hqErr'))
    pg.fill('#hqQty','20'); pg.click('#hqAdd'); pg.wait_for_timeout(200)
    t=pg.evaluate("tally()")
    chk("1箱・20個で記録",t['hit']==3 and pg.evaluate("tally().piecesByBin.get('1').get('JH001-001810-1')")==60)
    h=pg.evaluate("tally().history.at(-1)")
    chk("手入力の印",h['manual'] and h['hand'] and h['bin']=="1",h)
    chk("結果に「手入力 +20個」","手入力 +20個" in pg.inner_text('#scanResult'),pg.inner_text('#scanResult'))
    chk("読取順の一覧に「手入力」","手入力" in pg.inner_text('#scanHistory'))
    pg.click('#bUndo'); pg.wait_for_timeout(200)
    chk("取消できる",pg.evaluate("tally().hit")==2)
    print("== 5. 手入力の途中でハンディが読んだ")
    pg.focus('#scanIn'); pg.keyboard.type("JH",delay=180); pg.wait_for_timeout(300)
    pg.keyboard.type(A,delay=5); pg.wait_for_timeout(500)
    chk("ハンディの読取を優先して記録",pg.evaluate("tally().hit")==3,pg.evaluate("tally().hit"))
    chk("打ちかけは捨てたと表示","打ちかけ" in pg.inner_text('#handWarn'))
    chk("JSエラーなし",not errs,errs)
    print("RESULT",sum(R),"/",len(R))
